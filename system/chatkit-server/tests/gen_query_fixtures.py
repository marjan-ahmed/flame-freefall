"""Regenerate psi-data/query-fixtures.json — the golden cases BOTH query
implementations (psi_query.py here, system/site/lib/psi-query.ts) must
reproduce. Run after an intentional change to the query rules or the data,
review the diff, commit:

    uv run python tests/gen_query_fixtures.py
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import psi_query  # noqa: E402

FIXTURES = Path(__file__).resolve().parents[3] / "psi-data" / "query-fixtures.json"

CASES = [
    ("headline: ~15% O2, ~10 cm/s, PMMA", {"o2_pct": 15, "flow_cm_s": 10, "fuel_family": "PMMA"}, None),
    ("SIBAL fabric near air at 20 cm/s", {"o2_pct": 21, "flow_cm_s": 20, "fuel_family": "sibal"}, None),
    ("n-heptane droplets in air at 1 atm", {"o2_pct": 21, "pressure_atm": 1, "fuel_family": "n-heptane"}, None),
    ("gas flames at 25 cm/s coflow", {"flow_cm_s": 25, "geometry_class": "gaseous-flames"}, None),
    ("reduced pressure, elevated O2 (any fuel)", {"o2_pct": 30, "pressure_atm": 0.55}, None),
    ("methanol droplets at 15% O2, tight tolerance", {"o2_pct": 15, "fuel_family": "methanol"}, {"o2_pct": 0.5}),
    ("categorical only: SAFFIRE-2", {"investigation": "saffire-2"}, None),
    ("opposed-flow PMMA, 5 cm/s", {"flow_cm_s": 5, "fuel_family": "PMMA", "flow_direction": "opposed"}, None),
]


def expect(result: dict) -> dict:
    return {
        "counts": result["counts"],
        "match_ids": [v["id"] for v in result["match"][:15]],
        "partial_ids": [v["id"] for v in result["partial"][:15]],
        "near_ids": [v["id"] for v in result["near"][:5]],
        "coverage": {c["investigation_id"]: {k: a.get("target_in_range") for k, a in c["axes"].items()}
                     for c in result["coverage"]},
        "relaxed": result["relaxed"],
    }


def build() -> dict:
    cases = []
    for name, q, tol in CASES:
        cases.append({"name": name, "query": q, "tolerances": tol,
                      "expect": expect(psi_query.query(q, tolerances=tol))})
    return {"note": "generated by system/chatkit-server/tests/gen_query_fixtures.py — do not hand-edit",
            "cases": cases}


if __name__ == "__main__":
    FIXTURES.write_text(json.dumps(build(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {FIXTURES}")
