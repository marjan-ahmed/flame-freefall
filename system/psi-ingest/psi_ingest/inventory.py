"""`uv run psi-inventory` — a mechanical inventory of every raw PSI file:
name, row counts, column headers, workbook sheets.

It is the verification ground truth for the knowledge/data-sources/ documents
(the same role a converted PDF plays for an investigation document): those
documents may only state counts and column names that appear here, and
`.agents/skills/add-sources/verify.mjs` checks that they do. Generated; never
hand-edit psi-data/derived/source-inventory.md.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path

import openpyxl

REPO_ROOT = Path(__file__).resolve().parents[3]
RAW = REPO_ROOT / "psi-data" / "raw"
OUT = REPO_ROOT / "psi-data" / "derived" / "source-inventory.md"
SKIP = {"BASS Test Matrix 050213.xlsx"}  # carries credentials; never opened (see psi-data/README.md)


def _csv_rows(path: Path) -> list[list[str]]:
    for enc in ("utf-8-sig", "cp1252"):
        try:
            with path.open(encoding=enc, newline="") as f:
                return list(csv.reader(f))
        except UnicodeDecodeError:
            continue
    return []


def main() -> None:
    lines = ["# PSI raw file inventory (generated by system/psi-ingest psi-inventory)", ""]
    lines += ["## Experimental tables (psi-data/raw/csvs)", ""]
    for p in sorted((RAW / "csvs").glob("*.csv")):
        rows = _csv_rows(p)
        header = [re.sub(r"\s+", " ", h.replace("﻿", "")).strip() for h in rows[0]] if rows else []
        body = rows[1:]
        nonblank = sum(1 for r in body if any(c.strip() for c in r))
        m = re.match(r"(PSI-\d+)", p.name)
        lines.append(f"### {p.name}")
        lines.append(f"- dataset: {m.group(1) if m else 'none in file name'}")
        lines.append(f"- data rows: {len(body)}; non-blank data rows: {nonblank}")
        lines.append(f"- columns ({len(header)}): " + " | ".join(header))
        lines.append("")
    for folder in ("matrices", "summaries"):
        lines += [f"## Workbooks (psi-data/raw/{folder})", ""]
        for p in sorted((RAW / folder).iterdir()):
            lines.append(f"### {p.name}")
            if p.name in SKIP:
                lines += ["- not opened: contains account credentials", ""]
                continue
            if p.suffix.lower() != ".xlsx":
                lines += [f"- format: {p.suffix} (not inventoried)", ""]
                continue
            wb = openpyxl.load_workbook(p, read_only=True, data_only=True)
            lines.append(f"- sheets: {len(wb.worksheets)}")
            for ws in wb.worksheets:
                first = next(ws.iter_rows(max_row=1, values_only=True), ())
                head = [str(c).strip() for c in first if c is not None and str(c).strip()]
                lines.append(f"- sheet '{ws.title}': {ws.max_row} rows; first row: " + " | ".join(head[:12]))
            lines.append("")
    lines += ["## Reports (psi-data/raw/reports)", ""]
    lines += [f"- {p.name}" for p in sorted((RAW / "reports").glob("*.pdf"))]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"psi-inventory: wrote {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
